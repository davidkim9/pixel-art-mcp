/**
 * Data model (spec §4). These types are plain data so they can be shared with
 * the game and serialized to the native JSON project format.
 */

export type PaletteIndex = number; // 0 = transparent

export const DOC_KINDS = ["sprite", "character", "tileset", "effect", "icon"] as const;
export type DocKind = (typeof DOC_KINDS)[number];

export type BlendMode = "normal" | "additive";
export const TAG_DIRECTIONS = ["forward", "reverse", "pingpong", "pingpong_reverse"] as const;
export type TagDirection = (typeof TAG_DIRECTIONS)[number];
export type SymmetryMode = "none" | "horizontal" | "vertical" | "both";

/** "down" | "up" | "left" | "right" | "down_left" | ... — any name works. */
export type Direction = string;

export interface Point {
  x: number;
  y: number;
}

export interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface Palette {
  id: string;
  name: string;
  /** "#rrggbb", index-aligned; colors[0] is ignored (transparent). */
  colors: string[];
  /** Named shading ramps, dark → light, e.g. { skin: [12, 13, 14, 15] }. */
  ramps: Record<string, PaletteIndex[]>;
}

export interface Layer {
  id: string;
  name: string;
  visible: boolean;
  locked: boolean;
  blend: BlendMode;
  /** Guide layers are shown faintly in previews and never exported. */
  guide?: boolean;
}

export interface Frame {
  durationMs: number;
  tag?: string;
  /** Pivot in canvas pixels (continuous coordinates: 0 = left edge, width = right edge). */
  pivot?: Point;
  /** Free-form label shown in previews (corner masks, icon names, directions). */
  label?: string;
}

export interface RigPart {
  layerId: string;
  parent?: string;
  /** Rotation/anchor point, in canvas pixels. */
  pivot: Point;
  /** Where this part sits on its parent, in the parent's (canvas) pixels. */
  attachPoint?: Point;
  /** Per-direction overrides (written by mirror_rig or define_rig_part with a direction). */
  byDirection?: Record<Direction, { pivot?: Point; attachPoint?: Point }>;
}

export interface PosePart {
  dx: number;
  dy: number;
  flipX?: boolean;
  hidden?: boolean;
}

export interface Pose {
  name: string;
  parts: Record<string, PosePart>;
}

export interface Rig {
  parts: RigPart[];
  /** Frame i of a character document holds the parts drawn for directions[i]. */
  directions: Direction[];
  /** Layer ids back → front, per direction. */
  drawOrder: Record<Direction, string[]>;
  poses: Pose[];
  /** Directions generated by mirror_rig: target → source. Poses are mirrored automatically for them. */
  mirrors?: Record<Direction, Direction>;
}

export type TilesetTemplate = "corner15" | "blob47";

export interface TilesetConfig {
  tileSize: number;
  wrapDrawing: boolean;
  template?: TilesetTemplate;
  terrains?: { lower: string; upper: string };
  /** true: "lower" corners are transparent (index 0), drawn over a separate base. */
  overlay?: boolean;
}

export interface IconStyle {
  outline?: { color: number; connectivity: 4 | 8 } | null;
  shadow?: { color: number; dx: number; dy: number } | null;
}

export interface IconConfig {
  size: number;
  /** Width of the safe-area margin in pixels. */
  margin: number;
  /** Last style applied by apply_icon_style. */
  style?: IconStyle;
}

/** How an imported document is written back by export_to_source. */
export type ExportConfig =
  | { type: "png" }
  | { type: "spritesheet"; layout: SheetLayout; padding: number; extrude: number; tag?: string; columns?: number }
  | { type: "tileset"; columns?: number }
  | { type: "icons"; columns?: number }
  | { type: "character"; mode: "atlas" }
  | { type: "rects"; width: number; height: number; rects: Array<Rect & { offsetX: number; offsetY: number }> };

export type SheetLayout = "row" | "grid" | "packed";

export interface SourceInfo {
  path: string;
  format: "png" | "aseprite";
  importedAt: string;
  sha256: string;
  /** Integer upscale factor detected at import; export_to_source scales back up. */
  scale?: number;
  exportConfig?: ExportConfig;
  /** Export name used by the original MCP export (from its metadata). */
  assetName?: string;
}

export interface SymmetryState {
  mode: SymmetryMode;
  /** Mirror axes in continuous canvas coordinates (default: canvas center). */
  axisX: number;
  axisY: number;
}

export interface Document {
  id: string;
  name: string;
  kind: DocKind;
  width: number;
  height: number;
  paletteId: string;
  layers: Layer[]; // bottom → top
  frames: Frame[];
  /** key `${layerId}:${frameIndex}`, length width*height. Missing cels are fully transparent. */
  cels: Record<string, Uint8Array>;
  rig?: Rig;
  tileset?: TilesetConfig;
  icon?: IconConfig;
  source?: SourceInfo;
  symmetry?: SymmetryState;
  /** Wrap-around drawing for non-tileset documents (tilesets use tileset.wrapDrawing). */
  wrap?: boolean;
  /** Playback direction per tag name (default "forward"). */
  tagDirections?: Record<string, TagDirection>;
}

export type MetadataMode = "sidecar" | "embedded" | "both";

export interface ProjectSettings {
  pixelsPerUnit: number;
  outputDir: string;
  defaultPaletteId?: string;
  atlasPadding: number;
  atlasExtrude: number;
  metadataMode: MetadataMode;
  emitTsManifest: boolean;
  /** Directories the server may read existing assets from (besides the project root and outputDir). */
  importRoots: string[];
  /** Character export format: one atlas, or one PNG per part and direction. */
  characterExport: "atlas" | "parts";
}

