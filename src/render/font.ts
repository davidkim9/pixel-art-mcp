const PARSED = new Map<string, boolean[][]>();
for (const [ch, rows] of Object.entries(GLYPHS)) {
  PARSED.set(ch, rows.split(" ").map((r) => [...r].map((c) => c === "#")));
}

export const GLYPH_W = 3;
export const GLYPH_H = 5;

export function glyph(ch: string): boolean[][] {
  return PARSED.get(ch.toUpperCase()) ?? PARSED.get("?")!;
}

/** Width in pixels of `text` at the given scale (1px spacing between glyphs, scaled). */
export function textWidth(text: string, scale: number): number {
  if (text.length === 0) return 0;
  return text.length * (GLYPH_W + 1) * scale - scale;
}

export function textHeight(scale: number): number {
  return GLYPH_H * scale;
}
