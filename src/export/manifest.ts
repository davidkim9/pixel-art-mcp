import fs from "node:fs";
import path from "node:path";
import { readPngInfo } from "../png.js";
import type { Project } from "../project.js";
import { METADATA_KEYWORD } from "./metadata.js";
import type { AssetMetadata } from "./metadata.js";

export const MANIFEST_FILE = "assets.generated.ts";

export function isAssetMetadata(value: unknown): value is AssetMetadata {
  if (!value || typeof value !== "object") return false;
  const v = value as Record<string, unknown>;
  return typeof v.version === "number" && Array.isArray(v.frames) && typeof v.size === "object" && (typeof v.image === "string" || v.image === undefined);
}

function walk(dir: string, out: string[]): void {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    if (e.name.startsWith(".") || e.name === "node_modules") continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
}

export interface FoundAsset {
  key: string;
  dir: string;
  meta: AssetMetadata;
}

/** Every exported asset under outputDir, from sidecar JSON or embedded PNG metadata. */
export function scanAssets(outputDir: string): FoundAsset[] {
  const files: string[] = [];
  walk(outputDir, files);
  const found = new Map<string, FoundAsset>();
  const keyOf = (file: string) => path.relative(outputDir, file).replace(/\.[^.]+$/, "").split(path.sep).join("/");
  for (const file of files.filter((f) => f.endsWith(".json"))) {
    try {
      const meta = JSON.parse(fs.readFileSync(file, "utf8")) as unknown;
      if (isAssetMetadata(meta)) found.set(keyOf(file), { key: keyOf(file), dir: path.dirname(file), meta });
    } catch {
      // not ours
    }
  }
  const referenced = new Set<string>();
  for (const a of found.values()) {
    for (const img of [a.meta.image, a.meta.glow, ...a.meta.frames.map((f) => f.image)]) {
      if (typeof img === "string") referenced.add(path.join(a.dir, img));
    }
  }
  for (const file of files.filter((f) => f.endsWith(".png"))) {
    if (found.has(keyOf(file)) || referenced.has(file)) continue;
    try {
      const info = readPngInfo(fs.readFileSync(file));
      const text = info.texts.find((t) => t.keyword === METADATA_KEYWORD);
      if (!text) continue;
      const meta = JSON.parse(text.text) as unknown;
      if (isAssetMetadata(meta)) found.set(keyOf(file), { key: keyOf(file), dir: path.dirname(file), meta });
    } catch {
      // not a readable PNG
    }
  }
  return [...found.values()].sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

function indent(text: string, spaces: number): string {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line, i) => (i === 0 ? line : pad + line))
    .join("\n");
}

/** Regenerates outputDir/assets.generated.ts from the metadata on disk. */
export function writeManifest(project: Project): { path: string; assets: number } {
  const outputDir = project.outputDir;
  const assets = scanAssets(outputDir);
  const url = (dir: string, file: string) => project.displayPath(path.join(dir, file));
  const lines: string[] = [
    "// assets.generated.ts — do not edit",
    "// Generated by pixel-art-mcp from the asset metadata in this directory.",
    "export const assets = {",
  ];
  for (const a of assets) {
    const m = a.meta;
    const entry: Record<string, unknown> = {};
    if (m.image) entry.url = url(a.dir, m.image);
    if (m.glow) entry.glowUrl = url(a.dir, m.glow);
    entry.kind = m.kind;
    entry.size = m.size;
    entry.pixelsPerUnit = m.pixelsPerUnit;
    entry.frames = m.frames.map((f) => (typeof f.image === "string" ? { ...f, url: url(a.dir, f.image) } : f));
    entry.tags = Object.fromEntries((m.tags ?? []).map((t) => [t.name, [t.from, t.to]]));
    if ((m.tags ?? []).some((t) => t.direction !== "forward")) {
      entry.tagDirections = Object.fromEntries(m.tags.map((t) => [t.name, t.direction]));
    }
    if (m.tileset) entry.tileset = m.tileset;
    if (m.icons) entry.icons = m.icons;
    if (m.character) entry.character = m.character;
    lines.push(`  ${JSON.stringify(a.key)}: ${indent(JSON.stringify(entry, null, 2), 2)},`);
  }
  lines.push("} as const;", "", "export type AssetName = keyof typeof assets;", "");
  const file = path.join(outputDir, MANIFEST_FILE);
  fs.mkdirSync(outputDir, { recursive: true });
  fs.writeFileSync(file, lines.join("\n"));
  return { path: file, assets: assets.length };
}
